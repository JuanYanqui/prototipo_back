-- ---------- Tablas ----------
CREATE TABLE IF NOT EXISTS producto (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre   VARCHAR(120)   NOT NULL,
    precio   NUMERIC(12, 2) NOT NULL,
    stock    INTEGER        NOT NULL,
    version  BIGINT         NOT NULL DEFAULT 0,      -- bloqueo optimista
    CONSTRAINT ck_producto_stock_no_negativo CHECK (stock >= 0),
    CONSTRAINT ck_producto_precio_positivo  CHECK (precio > 0)
);

CREATE TABLE IF NOT EXISTS cliente (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identificacion VARCHAR(13)  NOT NULL,
    nombre         VARCHAR(120) NOT NULL,
    email          VARCHAR(120),
    CONSTRAINT uq_cliente_identificacion UNIQUE (identificacion)
);

CREATE TABLE IF NOT EXISTS venta (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT         NOT NULL REFERENCES cliente (id),
    vendedor   VARCHAR(255)   NOT NULL,
    fecha      TIMESTAMP(6)   NOT NULL,
    total      NUMERIC(12, 2) NOT NULL,
    CONSTRAINT ck_venta_total_no_negativo CHECK (total >= 0)
);

CREATE TABLE IF NOT EXISTS detalle_venta (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id        BIGINT         NOT NULL REFERENCES venta (id),
    producto_id     BIGINT         NOT NULL REFERENCES producto (id),
    cantidad        INTEGER        NOT NULL,
    precio_unitario NUMERIC(12, 2) NOT NULL,
    subtotal        NUMERIC(12, 2) NOT NULL,
    CONSTRAINT ck_detalle_cantidad_positiva CHECK (cantidad > 0)
);

CREATE INDEX IF NOT EXISTS ix_venta_fecha          ON venta (fecha);
CREATE INDEX IF NOT EXISTS ix_detalle_venta_venta  ON detalle_venta (venta_id);

