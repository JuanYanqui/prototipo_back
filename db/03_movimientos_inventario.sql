-- Table: public.movimiento_inventario

-- DROP TABLE IF EXISTS public.movimiento_inventario;

CREATE TABLE IF NOT EXISTS public.movimiento_inventario
(
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY ( INCREMENT 1 START 1 MINVALUE 1 MAXVALUE 9223372036854775807 CACHE 1 ),
    producto_id bigint NOT NULL,
    tipo_movimiento character varying(20) COLLATE pg_catalog."default" NOT NULL,
    cantidad integer NOT NULL,
    stock_anterior integer NOT NULL,
    stock_nuevo integer NOT NULL,
    motivo character varying(255) COLLATE pg_catalog."default",
    responsable character varying(120) COLLATE pg_catalog."default",
    fecha timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT movimiento_inventario_pkey PRIMARY KEY (id),
    CONSTRAINT movimiento_inventario_producto_id_fkey FOREIGN KEY (producto_id)
        REFERENCES public.producto (id) MATCH SIMPLE
        ON UPDATE NO ACTION
        ON DELETE NO ACTION,
    CONSTRAINT ck_cantidad_movimiento CHECK (cantidad > 0),
    CONSTRAINT ck_stock_movimiento CHECK (stock_anterior >= 0 AND stock_nuevo >= 0),
    CONSTRAINT ck_tipo_movimiento CHECK (tipo_movimiento::text = ANY (ARRAY['ENTRADA'::character varying, 'SALIDA'::character varying, 'AJUSTE'::character varying]::text[]))
)

TABLESPACE pg_default;

ALTER TABLE IF EXISTS public.movimiento_inventario
    OWNER to postgres;
-- Index: idx_movimiento_fecha

-- DROP INDEX IF EXISTS public.idx_movimiento_fecha;

CREATE INDEX IF NOT EXISTS idx_movimiento_fecha
    ON public.movimiento_inventario USING btree
    (fecha ASC NULLS LAST)
    TABLESPACE pg_default;
-- Index: idx_movimiento_producto

-- DROP INDEX IF EXISTS public.idx_movimiento_producto;

CREATE INDEX IF NOT EXISTS idx_movimiento_producto
    ON public.movimiento_inventario USING btree
    (producto_id ASC NULLS LAST)
    TABLESPACE pg_default;