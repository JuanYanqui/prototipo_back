DROP SCHEMA IF EXISTS public CASCADE;
CREATE SCHEMA public;
GRANT ALL ON SCHEMA public TO postgres;
GRANT ALL ON SCHEMA public TO public;

CREATE TABLE producto (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(120)   NOT NULL,
    precio       NUMERIC(12, 2) NOT NULL,
    stock        INTEGER        NOT NULL,
    stock_minimo INTEGER        NOT NULL DEFAULT 5,
    version      BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT ck_producto_stock_no_negativo CHECK (stock >= 0),
    CONSTRAINT ck_producto_precio_positivo  CHECK (precio > 0)
);

CREATE TABLE cliente (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identificacion VARCHAR(13)  NOT NULL,
    nombre         VARCHAR(120) NOT NULL,
    email          VARCHAR(120),
    CONSTRAINT uq_cliente_identificacion UNIQUE (identificacion)
);

CREATE TABLE venta (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT         NOT NULL REFERENCES cliente (id),
    vendedor   VARCHAR(255)   NOT NULL,
    fecha      TIMESTAMP(6)   NOT NULL,
    total      NUMERIC(12, 2) NOT NULL,
    CONSTRAINT ck_venta_total_no_negativo CHECK (total >= 0)
);

CREATE TABLE detalle_venta (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id        BIGINT         NOT NULL REFERENCES venta (id),
    producto_id     BIGINT         NOT NULL REFERENCES producto (id),
    cantidad        INTEGER        NOT NULL,
    precio_unitario NUMERIC(12, 2) NOT NULL,
    subtotal        NUMERIC(12, 2) NOT NULL,
    CONSTRAINT ck_detalle_cantidad_positiva CHECK (cantidad > 0)
);

CREATE TABLE usuario (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(40)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    nombre        VARCHAR(120) NOT NULL,
    rol           VARCHAR(20)  NOT NULL,
    activo        BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_usuario_username UNIQUE (username),
    CONSTRAINT ck_usuario_rol CHECK (rol IN ('ADMIN', 'VENDEDOR'))
);

CREATE TABLE movimiento_inventario (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id     BIGINT       NOT NULL REFERENCES producto (id),
    tipo_movimiento VARCHAR(20)  NOT NULL,
    cantidad        INTEGER      NOT NULL,
    stock_anterior  INTEGER      NOT NULL,
    stock_nuevo     INTEGER      NOT NULL,
    motivo          VARCHAR(255),
    responsable     VARCHAR(120),
    fecha           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_cantidad_movimiento CHECK (cantidad > 0),
    CONSTRAINT ck_stock_movimiento CHECK (stock_anterior >= 0 AND stock_nuevo >= 0),
    CONSTRAINT ck_tipo_movimiento CHECK (tipo_movimiento IN ('ENTRADA', 'SALIDA', 'AJUSTE'))
);

CREATE INDEX ix_venta_fecha          ON venta (fecha);
CREATE INDEX ix_detalle_venta_venta  ON detalle_venta (venta_id);
CREATE INDEX idx_movimiento_fecha    ON movimiento_inventario (fecha);
CREATE INDEX idx_movimiento_producto ON movimiento_inventario (producto_id);

